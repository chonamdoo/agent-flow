// 검증 루프 — 모든 에이전트에 필수
export const VERIFICATION_LOOP_RULES = `
## 검증 루프 (CODE→TEST→FIX→PASS)
모든 코드 변경 후 반드시 실행. 최대 3회 반복.

1. **CODE**: 변경사항 작성
2. **TEST**: 빌드 + 테스트 + 린트 실행
3. **FIX**: 실패 시 에러 분석 → 수정 (다음 라운드로)
4. **PASS**: 모든 검증 통과 → 다음 에이전트에 핸드오프

### 규칙
- 테스트 실패 시 테스트가 아닌 구현을 수정
- 3회 실패 시 에러 리포트와 함께 중단
- 각 라운드 결과를 이벤트로 기록
`

// 에이전트 간 통신 프로토콜
export const HANDOFF_PROTOCOL = `
## 핸드오프 프로토콜
에이전트 간 작업 전달 시:
1. 생성된 파일 목록 명시
2. 핵심 결정 사항 요약
3. 다음 에이전트에 필요한 컨텍스트 전달
4. 검증 루프 결과 포함 (PASS/FAIL + 라운드 수)
`

